# Hybrid retrieval — combine BM25 + embedding scores
def hybrid_retrieve(query, top_k=TOP_K):
    query_embed = model.encode([query])
    cos_scores = cosine_similarity(query_embed, embeddings)[0]

    bm25_scores = np.array(bm25.get_scores(query.lower().split()))
    if bm25_scores.max() > 0:
        bm25_scores = bm25_scores / bm25_scores.max()

    combined = 0.5 * cos_scores + 0.5 * bm25_scores
    return np.argsort(combined)[::-1][:top_k].tolist()


# Rerank candidates with BGE
def rerank_chunks(query, candidate_indices, top_n=TOP_RERANK):
    pairs = [[query, chunks[i]] for i in candidate_indices]
    scores = reranker.predict(pairs)  # CrossEncoder uses .predict()
    ranked = sorted(zip(scores, candidate_indices), reverse=True)
    return [chunks[idx] for _, idx in ranked[:top_n]]


