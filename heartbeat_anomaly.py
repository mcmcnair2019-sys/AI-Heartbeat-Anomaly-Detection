"""## Hybrid Retrieval and Re-ranking Functions"""

# BM25 index for hybrid retrieval
tokenized_chunks = [c.lower().split() for c in chunks]
bm25 = BM25Okapi(tokenized_chunks)

# BGE reranker
reranker = CrossEncoder("cross-encoder/ms-marco-MiniLM-L-6-v2")

# Hybrid retrieval — combine BM25 + embedding scores
def hybrid_retrieve(query, top_k=TOP_K):
    query_embed = model.encode([query])
    cos_scores = cosine_similarity(query_embed, embeddings)[0]

    bm25_scores = np.array(bm25.get_scores(query.lower().split()))
    if bm25_scores.max() > 0:
        bm25_scores = bm25_scores / bm25_scores.max()

    combined = 0.5 * cos_scores + 0.5 * bm25_scores
    return np.argsort(combined)[::-1][:top_k].tolist()


# Rerank candidates with BGE
def rerank_chunks(query, candidate_indices, top_n=TOP_RERANK):
    pairs = [[query, chunks[i]] for i in candidate_indices]
    scores = reranker.predict(pairs)  # CrossEncoder uses .predict()
    ranked = sorted(zip(scores, candidate_indices), reverse=True)
    return [chunks[idx] for _, idx in ranked[:top_n]]

# Simple embedding-only retrieval for System 2
# Simpler version of hybrid_retrieve(), no BM25, just embeddings.
# Used only for System 2
def simple_retrieve(query):
    # Turn the query into a vector
    query_vector = model.encode([query])

    # Score every chunk by how similar it is to the query
    scores = cosine_similarity(query_vector, embeddings)[0]

    # Return the top 2 chunk indices (highest scores first)
    top_indices = np.argsort(scores)[::-1][:TOP_RERANK]
    return top_indices.tolist()

