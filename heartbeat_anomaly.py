# Get label out of response
def parse_label(text):
    match = re.search(r'LABEL:\s*(Normal|PVC)', text, re.IGNORECASE)
    if match:
        return match.group(1)
    if re.search(r'\bPVC\b', text):
        return "PVC"
    if re.search(r'\bNormal\b', text, re.IGNORECASE):
        return "Normal"
    return "Unknown"


