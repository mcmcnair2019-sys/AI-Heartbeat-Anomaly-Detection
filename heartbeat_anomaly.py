def simple_retrieve(query):
    # Turn the query into a vector
    query_vector = model.encode([query])

    # Score every chunk by how similar it is to the query
    scores = cosine_similarity(query_vector, embeddings)[0]

    # Return the top 2 chunk indices (highest scores first)
    top_indices = np.argsort(scores)[::-1][:TOP_RERANK]
    return top_indices.tolist()



