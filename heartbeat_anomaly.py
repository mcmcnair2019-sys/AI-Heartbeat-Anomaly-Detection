"""## Data Extraction and Feature Engineering (ECG processing)"""

def extract_features(x, decimals=2):
    return {
        "mean": float(np.mean(x)),
        "variance": float(np.var(x)),
        "fft_mean_magnitude": float(np.mean(np.abs(np.fft.rfft(x)))),
        "signal_text": ", ".join(f"{v:.{decimals}f}" for v in x),
    }

rows = []
counts = {"Normal": 0, "PVC": 0}

for rec_name in tqdm(records):
    if all(c >= MAX_EACH for c in counts.values()):
        break
    try:
        record = wfdb.rdrecord(os.path.join(BASE_DIR, rec_name))
        ann = wfdb.rdann(os.path.join(BASE_DIR, rec_name), "atr")
    except Exception:
        continue

    fs = int(record.fs)
    lead_idx = record.sig_name.index("MLII") if "MLII" in record.sig_name else 0
    signal = record.p_signal[:, lead_idx]
    half = int((WINDOW_SEC / 2) * fs)

    for sample_idx, sym in zip(ann.sample, ann.symbol):
        label = LABEL_MAP.get(sym)
        if not label or counts[label] >= MAX_EACH:
            continue

        start, end = sample_idx - half, sample_idx + half
        if start < 0 or end > len(signal):
            continue

        # Resample to exact N_SAMPLES instead of integer-ratio approximation
        window = resample(signal[start:end], N_SAMPLES)
        rows.append({"label": label, "record": rec_name,
                     "beat_sample": sample_idx, **extract_features(window)})
        counts[label] += 1

print(f"Collected: {counts}")
